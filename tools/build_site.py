"""Assemble the site for hosting: the pages from public/ and the courses/ folder side by side in _site/.

Cloudflare Pages runs `python3 tools/build_site.py` and serves _site/, so the site lives at the
domain root (https://ieknowledgebase.nidhy.dev/) and the reader loads courses/<...> next to it.
public/ itself is generated by `python tools/roadmap_graph.py` and committed; this script only copies.
Standard library only.
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "_site"


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(ROOT / "public", OUT)
    shutil.copytree(ROOT / "courses", OUT / "courses")
    pages = len(list(OUT.glob("*.html")))
    files = sum(1 for p in (OUT / "courses").rglob("*") if p.is_file())
    print(f"_site/: {pages} pages, {files} course files")


if __name__ == "__main__":
    main()

"""Assemble the site for hosting: the pages from public/ and the courses/ folder side by side in _site/.

Cloudflare Pages runs `python3 tools/build_site.py` and serves _site/, so the site lives at the
domain root (https://theiehub.com/) and the reader loads courses/<...> next to it.
public/ itself is generated by `python tools/roadmap_graph.py` and committed; this script copies it
and writes _site/_headers, which Cloudflare Pages reads for response headers. The Content Security
Policy allows each page's inline scripts by their SHA-256 hash, so script-src needs no 'unsafe-inline'.
Standard library only.
"""
import base64
import hashlib
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "_site"

# Scripts: cdnjs (D3, anime.js, marked, DOMPurify, Mermaid). Styles: inline style attributes and the
# <style> blocks Mermaid writes into its SVGs need 'unsafe-inline'. Fonts: Google Fonts. Images:
# course figures from this site and data: URIs. fetch() only reads course files from this site.
CSP = ("default-src 'self'; script-src 'self' https://cdnjs.cloudflare.com {hashes}; "
       "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; "
       "img-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'self'; form-action 'none'; "
       "frame-ancestors 'none'")
COMMON = """  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: DENY
"""
INLINE_SCRIPT = re.compile(r"<script>(.*?)</script>", re.S)


def page_csp(html):
    hashes = sorted({"'sha256-" + base64.b64encode(hashlib.sha256(m.encode()).digest()).decode() + "'"
                     for m in INLINE_SCRIPT.findall(html)})
    return CSP.format(hashes=" ".join(hashes)).replace("  ", " ")


def write_headers():
    rules = ["/*\n" + COMMON]
    for page in sorted(OUT.glob("*.html")):
        csp = page_csp(page.read_text(encoding="utf-8"))
        paths = [f"/{page.name}"] + ([f"/{page.stem}"] if page.stem != "index" else ["/"])
        rules += [f"{p}\n  Content-Security-Policy: {csp}\n" for p in paths]
    (OUT / "_headers").write_text("\n".join(rules), encoding="utf-8")


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(ROOT / "public", OUT)
    shutil.copytree(ROOT / "courses", OUT / "courses")
    write_headers()
    pages = len(list(OUT.glob("*.html")))
    files = sum(1 for p in (OUT / "courses").rglob("*") if p.is_file())
    print(f"_site/: {pages} pages, {files} course files")


if __name__ == "__main__":
    main()
